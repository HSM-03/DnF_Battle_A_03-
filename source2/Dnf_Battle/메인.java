package Dnf_Battle;

/**
 * 메인 실행 데모
 * - 캐릭터생성 / 몬스터공격 / 아이템획득 / 길드가입 4개 유스케이스를
 *   정상 시나리오와 예외 시나리오(인증 실패, 인벤토리 초과, 길드 정원 초과)로 검증한다.
 */
public class 메인 {

    public static void main(String[] args) {
        전투 전투 = new 전투();

        System.out.println("===== 1. 캐릭터생성 =====");
        // 정상: 플레이어id == "hero"
        전투.캐릭터생성("hero", "두키", "전사", 5);
        // 실패: 잘못된 플레이어id
        전투.캐릭터생성("guest", "침입자", "마법사", 5);

        System.out.println("\n===== 2. 몬스터공격 =====");
        캐릭터 내캐릭터 = 전투.get캐릭터("hero");
        전투.몬스터공격("hero", 내캐릭터);   // 전사: 공격력(75) × 1.5 = 112.5 → A급

        System.out.println("\n===== 3. 아이템획득 =====");
        전투.아이템획득("hero", "둠스데이", "무기", 1200);   // 전설
        전투.아이템획득("hero", "강철갑옷", "방어구", 700);  // 희귀
        전투.아이템획득("hero", "체력물약", "물약", 100);    // 일반

        System.out.println("\n----- 인벤토리 초과 테스트 (10칸 한도) -----");
        for (int i = 4; i <= 11; i++) {
            전투.아이템획득("hero", "잡템" + i, "물약", 50);
        }

        System.out.println("\n===== 4. 길드가입 =====");
        // 길드는 외부에서 이미 생성된 객체 (Aggregation)
        길드 기존길드 = new 길드("불꽃군단");
        전투.길드등록(기존길드);
        전투.길드가입("hero", "불꽃군단");          // 정상 가입
        전투.길드가입("hero", "없는길드");          // 실패: 미등록 길드

        System.out.println("\n----- 길드 정원 초과 테스트 (5명 한도) -----");
        길드 만석길드 = new 길드("심연의탑");
        // 길드를 외부에서 미리 5명으로 채워둔다 (Aggregation: 다른 곳에서 생성된 캐릭터)
        for (int i = 1; i <= 5; i++) {
            만석길드.캐릭터가입(new 전사("용병" + i, 3));
        }
        전투.길드등록(만석길드);
        전투.길드가입("hero", "심연의탑");          // 실패: 정원(5/5) 초과

        System.out.println("\n===== 데모 종료 =====");
    }
}
